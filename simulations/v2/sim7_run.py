"""SIM 7 runner: sim-coverage audit of the FINAL V2 values.

Every case is its own netlist (generated from a sim7_*.cir template into sim7_runs/) and its
own LTspice process, with a hard timeout and a no-CPU-progress watchdog, so one stuck case
cannot block the rest.  Pattern follows sim5_run_split.py (fresh-log check, UTF-16 log
decoding, .meas parsing).  Only PIDs started here are ever killed.

Usage:  python sim7_run.py [group ...]
        groups: mon out ls chain1 chain2 ctran osc osc2 nocs  (default: all; chain2/ctran need chain1)
        only:<name-substring>,<group>[,<first opfix index>]   re-runs a subset of one group
Results are merged into sim7_results.json (one entry per case, saved as each case finishes).
Tables: python sim7_report.py (see sim7_README.md).
"""
import re, os, sys, json, time, subprocess, itertools
from concurrent.futures import ThreadPoolExecutor, as_completed
try:
    import psutil
except ImportError:
    psutil = None

HERE = os.path.dirname(os.path.abspath(__file__))
SIMS = os.path.dirname(HERE)
RUNS = os.path.join(HERE, "sim7_runs")
LT = r"C:\Users\lawre\AppData\Local\Programs\ADI\LTspice\LTspice.exe"
TIMEOUT = 240          # hard limit per case (s)
STALL = 60             # watchdog: kill if the process used no CPU for this long (s)
WORKERS = 4
RESULTS = os.path.join(HERE, "sim7_results.json")
os.makedirs(RUNS, exist_ok=True)


# ---------------------------------------------------------------- netlist generation
def _abs_includes(txt):
    def rep(m):
        name = m.group(1).strip()
        if name.startswith("../"):
            return ".include " + os.path.join(SIMS, name[3:]).replace("\\", "/")
        if name.endswith(".inc"):                       # inline local include files
            inc = open(os.path.join(HERE, name), encoding="utf-8").read()
            return "* ---- inlined " + name + " ----\n" + _abs_includes(inc) + "\n* ---- end " + name + " ----"
        return m.group(0)
    return re.sub(r"^\.include\s+(\S+)\s*$", rep, txt, flags=re.M | re.I)


# .op retry settings for the full-chain netlists (the LM8261/NE5532 macro-model .op search is
# erratic: the same netlist may converge in 5 s or give up after 140 s).  Only documented LTspice
# options are used (noopiter / gminsteps / srcstepmethod all appear in LTspice's own .op log).
FIXES = [
    ("none", None, None),
    ("srcstep1", "noopiter gminsteps=0 srcstepmethod=1", None),
    ("noopiter", "noopiter", None),
    ("gq3-0.05", "noopiter gminsteps=0", ("V(gq3)={VTQ3+0.1}", "V(gq3)={VTQ3-0.05}")),
    ("nonodeset", None, "STRIP_NODESETS"),
]
# the two full-chain templates use their own start-up routes (see the START-UP note in them)
CHAIN_FIXES = [
    ("op", None, None),
    ("hv0_150", None, "HV0=150"),
    ("startup", None, "STARTUP"),
    ("hv0_150+srcstep1", "noopiter gminsteps=0 srcstepmethod=1", "HV0=150"),
]
CHAIN_TEMPLATES = ("sim7_chain_dc.cir", "sim7_chain_tran.cir")
ATTEMPT_TIMEOUT = {"sim7_chain_dc.cir": 90}
RETRY_TEMPLATES = ("sim7_chain_dc.cir", "sim7_chain_tran.cir", "sim7_out_sine.cir", "sim7_out_step.cir",
                   "sim7_out_loop.cir", "sim7_ls_ac.cir", "sim7_ls_step.cir", "sim7_ls_sine.cir")


def fixes_for(template):
    return CHAIN_FIXES if template in CHAIN_TEMPLATES else FIXES


def make(template, name, params=None, gear=False, fix=0, nocs=False):
    txt = open(os.path.join(HERE, template), encoding="utf-8").read()
    txt = _abs_includes(txt)
    for k, v in (params or {}).items():
        pat = re.compile(r"^(\.param\b.*?\s)" + re.escape(k) + r"=\S+", re.M)
        txt, n = pat.subn(lambda m: m.group(1) + f"{k}={v}", txt, count=1)
        if n != 1:
            raise ValueError(f"{template}: .param {k} not found")
    if gear:
        txt = re.sub(r"^(\.options\b)", r"\1 method=gear", txt, count=1, flags=re.M)
    if nocs:                         # drop Sim 2's 'cshunt=1e-12' (1 pF on EVERY node, incl. op-amp internals)
        txt, n = re.subn(r"^(\.options\b.*?)\s+cshunt=\S+", r"\1", txt, flags=re.M)
        assert n >= 1, template + ": no cshunt to remove"
    fname, fopt, frep = fixes_for(template)[fix]
    if fopt:
        txt = re.sub(r"^(\.options\b)", r"\1 " + fopt, txt, count=1, flags=re.M)
    if frep in ("STRIP_NODESETS", "STARTUP"):
        txt = re.sub(r"^\.nodeset\b.*$", "* (nodeset removed by opfix)", txt, flags=re.M)
        if frep == "STARTUP":
            txt = re.sub(r"^(\.tran\b.*)$", r"\1 startup", txt, count=1, flags=re.M)
    elif frep == "HV0=150":
        txt, n = re.subn(r"^\.param HV0=\S+", ".param HV0=150", txt, count=1, flags=re.M)
        assert n == 1
    elif frep and frep[0] in txt:
        txt = txt.replace(*frep)
    txt = f"* generated by sim7_run.py from {template}  params={params}  gear={gear}  opfix={fname}  nocshunt={nocs}\n" + txt
    path = os.path.join(RUNS, f"sim7_{name}.cir")
    open(path, "w", encoding="utf-8").write(txt)
    return dict(name=name, path=path, template=template, params=params or {}, gear=gear, fix=fix, nocs=nocs)


# ---------------------------------------------------------------- log parsing
NUM = r"[-+]?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?"

def parse_log(txt):
    res, fails, steps = {}, [], {}
    for line in txt.splitlines():
        m = re.match(r"^(\w+):\s+(.*)$", line)
        if m and m.group(1).lower() not in ("measurement", "circuit", "options", "files", "warning", "solver"):
            key, rest = m.group(1).lower(), m.group(2)
            if "FAIL" in rest.upper():
                fails.append(key); continue
            c = re.search(r"=\(\s*(" + NUM + r")dB,\s*(" + NUM + r")", rest)
            if c:
                res[key + "_db"] = float(c.group(1)); res[key + "_deg"] = float(c.group(2)); continue
            v = re.search(r"=\s*(" + NUM + r")", rest)
            if v:
                res[key] = float(v.group(1))
            a = re.search(r"\sAT\s+(" + NUM + r")\s*$", rest, re.I)     # WHEN results: the crossing point
            if a:
                res[key + "_at"] = float(a.group(1))
    # stepped tables:  "Measurement: name" / header / rows "  i  value ..."
    for blk in re.finditer(r"Measurement:\s*(\w+)\s*\n[^\n]*\n((?:\s+\d+\s+[^\n]*\n)+)", txt):
        vals = []
        for row in blk.group(2).splitlines():
            parts = row.split()
            if len(parts) >= 2:
                c = re.match(r"\(\s*(" + NUM + r")dB", parts[1])
                vals.append(float(c.group(1)) if c else (float(parts[1]) if re.fullmatch(NUM, parts[1]) else parts[1]))
        steps[blk.group(1).lower()] = vals
    for m in re.finditer(r"Measurement \"?(\w+)\"? FAIL", txt, re.I):
        fails.append(m.group(1).lower())
    thd = re.findall(r"Total Harmonic Distortion:\s*(" + NUM + r")%", txt)
    if thd:
        res["thd_pct"] = float(thd[-1])
    if steps:
        res["_steps"] = steps
    return res, sorted(set(fails))


# ---------------------------------------------------------------- running
def _rm(fn, tries=10):
    """Delete a scratch file; tolerate a short lock (LTspice just exiting, OneDrive sync)."""
    for _ in range(tries):
        try:
            os.remove(fn); return True
        except FileNotFoundError:
            return True
        except PermissionError:
            time.sleep(0.5)
    return False


def run(job):
    path = job["path"]; base = path[:-4]
    for ext in (".log", ".raw", ".op.raw"):
        _rm(base + ext)
    t0 = time.time()
    p = subprocess.Popen([LT, "-b", path], cwd=RUNS)
    status, last_cpu, last_prog = "ok", -1.0, time.time()
    while True:
        try:
            p.wait(timeout=2); break
        except subprocess.TimeoutExpired:
            pass
        now = time.time()
        if now - t0 > ATTEMPT_TIMEOUT.get(job["template"], TIMEOUT):
            status = "TIMEOUT"; break
        if psutil:
            try:
                ct = psutil.Process(p.pid).cpu_times(); cpu = ct.user + ct.system
                if cpu > last_cpu + 0.05:
                    last_cpu, last_prog = cpu, now
                elif now - last_prog > STALL:
                    status = "HUNG (no CPU progress)"; break
            except psutil.NoSuchProcess:
                pass
    if p.poll() is None:                     # kill only what we started (+ its children)
        if psutil:
            try:
                for ch in psutil.Process(p.pid).children(recursive=True):
                    ch.kill()
            except psutil.NoSuchProcess:
                pass
        p.kill(); p.wait()
    dt = time.time() - t0
    res, fails, err = {}, [], ""
    log = base + ".log"
    if os.path.exists(log) and os.path.getmtime(log) >= t0 - 1:      # freshness check
        raw = open(log, "rb").read()
        txt = raw.decode("utf-16-le", errors="ignore") if b"\x00" in raw[:200] else raw.decode("latin-1")
        res, fails = parse_log(txt)
        e = re.findall(r"^(.*(?:[Ee]rror|singular|Timestep too small|convergence failed)[^\n]*)$", txt, re.M)
        err = " | ".join(e[:3])
        if status == "ok" and re.search(r"skipping operating point|Trouble finding operating point", txt, re.I):
            status = "OP FAILED"          # transient would have started from an all-zero state
        if status == "ok" and not res:
            status = "NO MEASUREMENTS"
    elif status == "ok":
        status = "NO FRESH LOG"
    for ext in (".raw", ".op.raw"):
        _rm(base + ext)
    with open(os.path.join(HERE, "sim7_progress.txt"), "a") as f:
        f.write(f"{time.strftime('%H:%M:%S')} {job['name']} {status} {dt:.1f}s\n")
    return job["name"], dict(status=status, t=round(dt, 1), template=job["template"],
                             params=job["params"], gear=job["gear"], nocshunt=job.get("nocs", False), opfix=fixes_for(job["template"])[job.get("fix", 0)][0],
                             meas=res, fails=fails, err=err)


def _one(job):
    """Run a case; for the chain templates retry with the next .op fix until one works."""
    history = []
    while True:
        name, r = run(job)
        history.append(f"{r['opfix']}:{r['status']}")
        if r["status"] == "ok" or job["template"] not in RETRY_TEMPLATES or job["fix"] + 1 >= len(fixes_for(job["template"])):
            r["tries"] = history
            return name, r
        job = make(job["template"], name, job["params"], job["gear"], fix=job["fix"] + 1, nocs=job.get("nocs", False))


def run_all(jobs):
    """Run all jobs; each result is saved to sim7_results.json as soon as it arrives, so an
    interrupted batch keeps everything that finished (the save runs in this thread only)."""
    out = {}
    with ThreadPoolExecutor(max_workers=WORKERS) as ex:
        futs = [ex.submit(_one, j) for j in jobs]
        for fut in as_completed(futs):
            try:
                name, r = fut.result()
            except Exception as e:                      # never lose the rest of the batch
                print("CASE CRASHED:", repr(e), flush=True); continue
            out[name] = r
            save({name: r})
            print(f"{name:40s} {r['status']:10s} {r['t']:6.1f}s  {' > '.join(r['tries'])}", flush=True)
    return out


def load():
    try: return json.load(open(RESULTS))
    except (FileNotFoundError, json.JSONDecodeError): return {}


def save(res):
    allr = load(); allr.update(res)
    json.dump(allr, open(RESULTS, "w"), indent=1, sort_keys=True)


