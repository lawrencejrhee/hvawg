        cls = ("22p", "100p") if hv == 150 else ("22p",)
        for cl in cls:
            j.append(make("sim7_chain_tran.cir", f"ctran_step_{hv}_{cl}", {"HV": hv, "RFIX": f"{rc:.3f}", "CL": cl, "MODEW": 0}))
