def g_nocs():
    """cshunt check.  The out_* templates inherit 'cshunt=1e-12' from Sim 2.  LTspice adds that 1 pF to
    EVERY node, including the ~50 internal nodes of the LM8261 macro-model (whose only explicit
    capacitor is its 8 pF Miller cap), which adds poles near the ~1 MHz loop crossover.  Sim 6 and the
    full-chain sim7_chain_tran.cir do not use it.  Re-run the stability cases without it to separate a
    model artefact from a real limit cycle."""
    j = []
    def both(tag, p):
        j.append(make("sim7_out_step.cir", f"nocs_step_{tag}", p, nocs=True))
        j.append(make("sim7_out_loop.cir", f"nocs_loop_{tag}", p, nocs=True))
    for hv, vdc in ((150, 0.15), (150, 1.125), (150, 2.1), (50, 0.375)):
        for cl in ("10p", "22p", "47p", "100p"):
            both(f"{hv}_{vdc}_{cl}", {"HV": hv, "VDC": vdc, "CL": cl})
    for cl in ("22p", "47p", "100p"):                                    # Crss-floor sensitivity
        both(f"150_1.125_{cl}_cgd20p", {"HV": 150, "VDC": 1.125, "CL": cl, "CGDMIN": "20p"})
    both("150_0.75_100p_r22_50", {"HV": 150, "VDC": 0.75, "CL": "100p", "R22V": 50})
    both("150_1.125_1n", {"HV": 150, "VDC": 1.125, "CL": "1n"})           # abuse case: ~10 m of coax
    for hv, cl in itertools.product((150, 50), ("10p", "22p", "47p", "100p")):
        j.append(make("sim7_out_sine.cir", f"nocs_sine_{hv}_{cl}", {"HV": hv, "CL": cl}, nocs=True))
    return j


GROUPS = dict(mon=g_mon, out=g_out, ls=g_ls, chain1=g_chain1, chain2=g_chain2, ctran=g_ctran, osc=g_osc,
              osc2=g_osc2, nocs=g_nocs)

if __name__ == "__main__":
    sel = sys.argv[1:] or list(GROUPS)
    for g in sel:
        if g.startswith("only:"):                 # only:<case-name-substring>,<group>[,<first opfix index>]
            parts = g[5:].split(",")
            sub, grp = parts[0], parts[1]
            jobs = [x for x in GROUPS[grp]() if sub in x["name"]]
            if len(parts) > 2:
                jobs = [make(x["template"], x["name"], x["params"], x["gear"], fix=int(parts[2]), nocs=x.get("nocs", False))
                        for x in jobs]
        else:
            jobs = GROUPS[g]()
        print(f"=== group {g}: {len(jobs)} cases", flush=True)
        save(run_all(jobs))
    print("done")
